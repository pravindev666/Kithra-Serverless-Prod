/**
 * TASK 4: Programmatic Verification & Psychometric Audit of the 60-Question Pilot Bank.
 * Checks construct coverage, option scoring validity, semanticId uniqueness,
 * translation completeness (en, ta, hi), duplicate prompts, and flags items
 * requiring human psychometric/cultural expert review prior to field calibration.
 */
export function auditPilotQuestionBank(
  questions: AssessmentQuestion[] = PILOT_60_QUESTION_BANK
): PilotQuestionBankAuditReport {
  const stageCounts: Record<1 | 2 | 3, number> = { 1: 0, 2: 0, 3: 0 };
  const formatCounts: Record<QuestionFormatType, number> = {
    direct_preference: 0,
    situational_judgment: 0,
    contextual_trait: 0,
    values_tradeoff: 0,
    forced_choice: 0,
    importance_boundary: 0,
    optional_reflection: 0,
  };
  const constructCoverage: Record<string, number> = {};
  const intentionScopeCounts: Record<IntentionId, number> = {
    friendship: 0,
    dating: 0,
    matrimony: 0,
  };

  const seenSemanticIds = new Set<string>();
  const seenPrompts = new Set<string>();
  let allHaveUniqueSemanticIds = true;
  let allHaveThreeLanguages = true;
  let allMarkedOriginalUnvalidated = true;
  let duplicatePromptsFound = 0;
  let allHaveScoringTypes = true;
  let allHaveResearchBasis = true;
  let allHaveMeasurementLimitations = true;
  let allHaveOptionTranslations = true;
  const scoringTypeCounts: Record<string, number> = {};
  const issues: QuestionAuditIssue[] = [];

  for (const q of questions) {
    const st = (typeof q.stage === 'number' ? q.stage : 1) as 1 | 2 | 3;
    stageCounts[st] = (stageCounts[st] ?? 0) + 1;

    if (q.formatType) {
      formatCounts[q.formatType] = (formatCounts[q.formatType] ?? 0) + 1;
    }

    const cid = q.constructId ?? 'unassigned';
    constructCoverage[cid] = (constructCoverage[cid] ?? 0) + 1;

    for (const intent of q.applicableIntentions) {
      intentionScopeCounts[intent] += 1;
    }

    if (q.validationStatus !== 'ORIGINAL / UNVALIDATED') {
      allMarkedOriginalUnvalidated = false;
    }

    if (!q.scoringType) {
      allHaveScoringTypes = false;
    } else {
      scoringTypeCounts[q.scoringType] = (scoringTypeCounts[q.scoringType] ?? 0) + 1;
    }

    if (!q.researchBasis || q.researchBasis.trim().length === 0) {
      allHaveResearchBasis = false;
    }

    if (!q.measurementLimitations || q.measurementLimitations.trim().length === 0) {
      allHaveMeasurementLimitations = false;
    }

    const normPrompt = q.prompt.trim().toLowerCase();
    if (seenPrompts.has(normPrompt)) {
      duplicatePromptsFound += 1;
      issues.push({
        questionId: q.id,
        questionNumber: q.questionNumber,
        severity: 'error',
        category: 'duplicate_prompt',
        detail: `Duplicate prompt detected: "${q.prompt}"`,
      });
    }
    seenPrompts.add(normPrompt);

    if (!q.translations?.ta || !q.translations?.hi) {
      allHaveThreeLanguages = false;
      issues.push({
        questionId: q.id,
        questionNumber: q.questionNumber,
        severity: 'warning',
        category: 'missing_translation',
        detail: 'Missing Tamil (ta) or Hindi (hi) translation.',
      });
    }

    for (const opt of q.options) {
      if (!opt.labelTa || !opt.labelHi) {
        allHaveOptionTranslations = false;
      }

      if (!opt.semanticId || seenSemanticIds.has(opt.semanticId)) {
        allHaveUniqueSemanticIds = false;
        issues.push({
          questionId: q.id,
          questionNumber: q.questionNumber,
          severity: 'error',
          category: 'invalid_option_scoring',
          detail: `Missing or duplicate option semanticId: ${opt.semanticId ?? opt.id}`,
        });
      } else {
        seenSemanticIds.add(opt.semanticId);
      }

      if (
        opt.normalizedValue === undefined ||
        opt.normalizedValue < 0 ||
        opt.normalizedValue > 100
      ) {
        issues.push({
          questionId: q.id,
          questionNumber: q.questionNumber,
          severity: 'error',
          category: 'invalid_option_scoring',
          detail: `Option ${opt.id} has out-of-range normalizedValue: ${opt.normalizedValue}`,
        });
      }
    }
  }

  // Flag specific items that require human psychometric & cultural expert review during pilot testing
  const expertReviewNotes: QuestionAuditIssue[] = [
    {
      questionId: 'q-15-honesty-tact-tradeoff',
      questionNumber: 15,
      severity: 'info_expert_review',
      category: 'psychometric_calibration_needed',
      detail:
        'Social-desirability check needed: Option "Share the truth gently" may attract >70% endorsement in pilot testing; review option phrasing during cognitive interviews.',
    },
    {
      questionId: 'q-20-heated-voice-anchor-a',
      questionNumber: 20,
      severity: 'info_expert_review',
      category: 'construct_overlap_note',
      detail:
        'Intentional paired consistency anchor with Q21 (emotional_regulation). Verify in pilot data that Q20 and Q21 correlate r >= 0.65 without feeling repetitive.',
    },
    {
      questionId: 'q-26-festival-celebration-context',
      questionNumber: 26,
      severity: 'info_expert_review',
      category: 'cultural_nuance_review',
      detail:
        'Contextual pair with Q27 (festivals vs. Friday post-work fatigue). Confirm across Tamil and Hindi speakers that wedding/festival social energy is separated from everyday extraversion.',
    },
    {
      questionId: 'q-51-extended-family-advice',
      questionNumber: 51,
      severity: 'info_expert_review',
      category: 'cultural_nuance_review',
      detail:
        'High cultural sensitivity in Indian matrimony: Ensure Tamil and Hindi translations of "elders’ perspectives" vs. "united couple voice" carry equal respect without stigma.',
    },
    {
      questionId: 'q-52-elder-caregiving',
      questionNumber: 52,
      severity: 'info_expert_review',
      category: 'cultural_nuance_review',
      detail:
        'Egalitarian caregiving item: Check for ceiling effects and verify whether a separate item on geographic proximity to parents is needed in Stage 3.',
    },
  ];

  return {
    totalQuestions: questions.length,
    stageCounts,
    formatCounts,
    constructCoverage,
    intentionScopeCounts,
    allHaveUniqueSemanticIds,
    allHaveThreeLanguages,
    allMarkedOriginalUnvalidated,
    duplicatePromptsFound,
    itemsFlaggedForHumanExpertReview: [...issues, ...expertReviewNotes],
    allHaveScoringTypes,
    allHaveResearchBasis,
    allHaveMeasurementLimitations,
    allHaveOptionTranslations,
    scoringTypeCounts,
  };
}
